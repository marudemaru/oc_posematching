using UnityEngine;

public class WallCollisionDetector : MonoBehaviour
{
    // ???????????????
    // Inspector??????????????????CameraShake??????????????????
    public CameraShake cameraShake;

    void OnTriggerEnter(Collider other)
    {
        // ????????Wall????????????
        if (other.CompareTag("Wall"))
        {
            // CameraShake?????????????????????
            if (cameraShake != null)
            {
                cameraShake.StartShake();
            }
        }
    }
}
